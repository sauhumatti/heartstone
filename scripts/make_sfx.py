#!/usr/bin/env python3
"""Make the game's recorded sound clips: creature voices and the heavier
combat and magic effects. (The light, tactile sounds are made in code, see
frontend/src/audio/bank.ts.)

Each clip is described in words below, generated by a text-to-audio model
(Seed Audio through OpenRouter, about $0.0025 per second), then trimmed to
its start, cut to length, levelled and written to frontend/public/sfx/.

    OPENROUTER_API_KEY=... python3 scripts/make_sfx.py            # make what is missing
    python3 scripts/make_sfx.py --redo dragon-enter fizzle        # make these again
    python3 scripts/make_sfx.py --process                         # only re-cut what was generated

Needs ffmpeg and numpy. Raw takes are kept in var/sfx-raw/ so a clip can be
re-cut without paying for it again.
"""
