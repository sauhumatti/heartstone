# Sounds that swell in rather than start with a bang: keep their quiet beginning.
SOFT_START = {"healing", "stealFx", "secretSet", "silenceFx"}
LOUDNESS_DB = -16.0  # of the loudest quarter second, to sit with the sounds made in code
PEAK_DB = -1.0


def generate(name: str, take: int, key: str) -> str:
    path = RAW / f"{name}-{take}.mp3"
    # the model takes the stated length literally, so the longer cries ask for two seconds
    length = "one second" if CLIPS[name][1] < 1.5 else "two seconds"
    text = f"A short game sound effect, about {length} long. " + CLIPS[name][2] + TAIL
    body = json.dumps({"model": MODEL, "input": text, "response_format": "mp3"}).encode()
    last = ""
    for attempt in range(4):
        req = urllib.request.Request(
            "https://openrouter.ai/api/v1/audio/speech",
            data=body,
            headers={"Authorization": "Bearer " + key, "Content-Type": "application/json"},
        )
        try:
            with urllib.request.urlopen(req, timeout=240) as res:
                data = res.read()
            if len(data) < 2000:
                raise ValueError(f"only {len(data)} bytes")
            path.write_bytes(data)
            return f"ok   {path.name}"
        except urllib.error.HTTPError as err:
            last = f"{err.code} {err.read()[:200].decode('utf-8', 'replace')}"
        except Exception as err:  # timeouts, resets
            last = repr(err)
        time.sleep(4 * (attempt + 1))
    return f"FAIL {path.name}: {last}"


def decode(path: Path) -> np.ndarray:
    raw = subprocess.run(
        ["ffmpeg", "-v", "error", "-i", str(path), "-ac", "1", "-ar", str(SR), "-f", "f32le", "-"],
        capture_output=True,
        check=True,
    ).stdout
    return np.frombuffer(raw, dtype=np.float32).astype(np.float64)


def envelope(x: np.ndarray, ms: float = 5.0) -> np.ndarray:
    n = max(1, int(SR * ms / 1000))
    pad = (-len(x)) % n
    blocks = np.abs(np.pad(x, (0, pad))).reshape(-1, n).max(axis=1)
    return np.repeat(blocks, n)[: len(x)]


def cut(x: np.ndarray, longest: float, soft: bool) -> np.ndarray:
    """Start at the sound, stop when it is over or at its longest, and set the level."""
    x = x - x.mean()
    env = envelope(x)
    peak = env.max()
    if peak <= 1e-5:
        raise ValueError("silent")
    loud = np.where(env > peak * (0.03 if soft else 0.07))[0]
    start = max(0, loud[0] - int(0.008 * SR))
    audible = np.where(env > peak * 0.006)[0]
    end = min(len(x), audible[-1] + int(0.03 * SR))
    limit = start + int(longest * SR)
    # cut short by us, or by the take itself running out while still sounding: fade it out, do not chop it
    clipped = end > limit or (end >= len(x) and env[-int(0.02 * SR):].max() > peak * 0.05)
    end = min(end, limit)
    y = x[start:end].copy()
    fade_in = min(len(y), int((0.02 if soft else 0.003) * SR))
    y[:fade_in] *= np.linspace(0, 1, fade_in)
    fade_out = min(len(y), int((min(0.3, 0.3 * len(y) / SR) if clipped else 0.03) * SR))
    y[-fade_out:] *= np.linspace(1, 0, fade_out) ** (2 if clipped else 1)
    # level: the loudest quarter second to a common loudness, without letting the peak clip
    w = min(len(y), int(0.25 * SR))
    power = np.convolve(y * y, np.ones(w) / w, mode="valid").max()
    gain = 10 ** (LOUDNESS_DB / 20) / np.sqrt(power + 1e-12)
    gain = min(gain, 10 ** (PEAK_DB / 20) / np.abs(y).max())
    return y * gain


def encode(y: np.ndarray, path: Path) -> None:
    subprocess.run(
        ["ffmpeg", "-v", "error", "-y", "-f", "f32le", "-ar", str(SR), "-ac", "1", "-i", "-",
         "-codec:a", "libmp3lame", "-b:a", "96k", str(path)],
        input=y.astype(np.float32).tobytes(),
        check=True,
    )


def process() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    manifest = {}
    total = 0
    for name, (takes, longest, _text) in CLIPS.items():
        made = 0
        for take in range(takes):
            raw = RAW / f"{name}-{take}.mp3"
            if not raw.exists():
                continue
            try:
                x = decode(raw)
                y = cut(x, longest, name in SOFT_START)
            except Exception as err:
                print(f"skip {raw.name}: {err}")
                continue
            # takes are numbered without gaps so the game can count on them
            out = OUT / f"{name}-{made}.mp3"
            encode(y, out)
            total += out.stat().st_size
            print(f"{out.name:26s} {len(x) / SR:5.2f}s -> {len(y) / SR:4.2f}s  peak {20 * np.log10(np.abs(y).max()):5.1f} dB")
            made += 1
        stale = OUT / f"{name}-{made}.mp3"
        while stale.exists():
            stale.unlink()
            made_next = int(stale.stem.rsplit("-", 1)[1]) + 1
            stale = OUT / f"{name}-{made_next}.mp3"
        if made:
            manifest[name] = made
        else:
            print(f"MISSING {name}")
    MANIFEST.write_text(json.dumps(manifest, indent=2) + "\n")
    print(f"{sum(manifest.values())} clips of {sum(c[0] for c in CLIPS.values())}, {total / 1024:.0f} KB -> {OUT}")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--redo", nargs="*", default=[], metavar="NAME", help="generate these clips again")
    ap.add_argument("--process", action="store_true", help="only re-cut the takes already generated")
    ap.add_argument("--workers", type=int, default=4)
    args = ap.parse_args()
    unknown = [n for n in args.redo if n not in CLIPS]
    if unknown:
        sys.exit(f"unknown clip(s): {', '.join(unknown)}")

    if not args.process:
        key = os.environ.get("OPENROUTER_API_KEY")
        if not key:
            sys.exit("set OPENROUTER_API_KEY (or use --process)")
        RAW.mkdir(parents=True, exist_ok=True)
        jobs = [
            (name, take)
            for name, (takes, _l, _t) in CLIPS.items()
            for take in range(takes)
            if name in args.redo or not (RAW / f"{name}-{take}.mp3").exists()
        ]
        print(f"generating {len(jobs)} take(s)")
        with ThreadPoolExecutor(max_workers=args.workers) as pool:
            for line in pool.map(lambda j: generate(j[0], j[1], key), jobs):
                print(line, flush=True)
    process()


if __name__ == "__main__":
    main()
