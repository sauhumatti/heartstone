from engine.catalog import COLLECTIBLE_BY_NAME, validate_deck


def _deck(entries: list[tuple[str, int]]) -> list[str]:
    out: list[str] = []
    for name, count in entries:
        card = COLLECTIBLE_BY_NAME[name]
        out.extend([card.id] * count)
    return out


